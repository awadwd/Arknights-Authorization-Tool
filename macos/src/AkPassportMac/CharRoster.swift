    /// 某分组可选值；「分支」随已选职业联动，未选职业时给出全部。
    static func options(of key: String, pickedProfessions: [String]) -> [String] {
        switch key {
        case "prof": return professions
        case "rar": return rarities
        case "pos": return positions
        case "sex": return genders
        case "obt": return obtains
        case "tag": return tags
        case "boxType": return boxTypes.map(\.value)
        case "sale": return saleTypes.map(\.value)
        case "rep": return replicateTypes.map(\.value)
        case "sub":
            // 未选职业时列出全部分支（跨职业可能有重名，保持首次出现的顺序去重）
            let keys = pickedProfessions.isEmpty ? Array(subProfessions.keys) : pickedProfessions
            var result: [String] = []
            for prof in keys {
                for sub in subProfessions[prof] ?? [] where !result.contains(sub) {
                    result.append(sub)
                }
            }
            return result
        default: return []
        }
    }

    /// 选项在界面上的文案（稀有度加星、盒类型 / 盲抽 / 复刻翻成中文）。
    static func label(of key: String, value: String) -> String {
        switch key {
        case "rar": return value + "★"
        case "boxType": return lookup(boxTypes, value)
        case "sale": return lookup(saleTypes, value)
        case "rep": return lookup(replicateTypes, value)
        case "year": return value + "年"
        default: return value
        }
    }

    private static func lookup(_ table: [Option], _ value: String) -> String {
        table.first { $0.value == value }?.label ?? value
    }
