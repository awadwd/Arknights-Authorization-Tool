using Microsoft.UI;
using Windows.UI;

namespace AkPassport.Win.Services;

/// <summary>
/// 壳的主题色板。前端有 6 套主题（simple / ak / ark / jieyuan / liquid / liquidDark），
/// 这里取各自「画布 / 面板 / 描边 / 文字 / 是否深色」，让侧边栏和内容卡片跟着变。
/// 取值来自 common/ak-theme.css 与 common/liquid-theme.css 的设计令牌。
/// </summary>
internal readonly record struct ShellTheme(
	Color Canvas,
	Color Pane,
	Color Panel,
	Color Border,
	Color Text,
	bool Dark)
{
	public static ShellTheme For(string? name) => (name ?? "").Trim().ToLowerInvariant() switch
	{
		"ark" => new ShellTheme(
			Hex(0x13, 0x14, 0x15), Hex(0x1B, 0x1D, 0x1E), Hex(0x1B, 0x1D, 0x1E),
			Hex(0x2C, 0x30, 0x32), Hex(0xEC, 0xEB, 0xE6), true),

		"liquiddark" => new ShellTheme(
			Hex(0x0F, 0x11, 0x14), Hex(0x17, 0x1A, 0x1E), Hex(0x17, 0x1A, 0x1E),
			Hex(0x2A, 0x2F, 0x36), Hex(0xE8, 0xEA, 0xED), true),

		"ak" => new ShellTheme(
			Hex(0xEF, 0xEF, 0xEC), Hex(0xFD, 0xFD, 0xFB), Hex(0xFD, 0xFD, 0xFB),
			Hex(0xDB, 0xDC, 0xD6), Hex(0x1B, 0x1D, 0x1F), false),

		"jieyuan" => new ShellTheme(
			Hex(0xFA, 0xF3, 0xE0), Hex(0xFF, 0xFD, 0xF7), Hex(0xFF, 0xFD, 0xF7),
			Hex(0xEB, 0xDF, 0xC6), Hex(0x4A, 0x3B, 0x2E), false),

		// Windows 版默认主题：液态玻璃（simple 已从 Windows 版移除）
		_ => new ShellTheme(
			Hex(0xEC, 0xF1, 0xF7), Hex(0xFA, 0xFC, 0xFF), Hex(0xFA, 0xFC, 0xFF),
			Hex(0xDD, 0xE4, 0xEE), Hex(0x1C, 0x22, 0x2B), false),
	};

	private static Color Hex(byte r, byte g, byte b) => Color.FromArgb(0xFF, r, g, b);
}
